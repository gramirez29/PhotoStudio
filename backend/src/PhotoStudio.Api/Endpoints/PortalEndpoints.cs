using System.Security.Claims;
using Microsoft.AspNetCore.Http.HttpResults;
using PhotoStudio.Api.RateLimiting;
using PhotoStudio.Application.Abstractions;
using PhotoStudio.Application.Portal;
using PhotoStudio.Application.Portal.GetBooking;
using PhotoStudio.Application.Portal.RequestCode;
using PhotoStudio.Application.Portal.SubmitProof;
using PhotoStudio.Application.Portal.VerifyCode;
using PhotoStudio.Infrastructure.Portal;

namespace PhotoStudio.Api.Endpoints;

/// <summary>
/// HTTP body to verify the code the client received.
/// </summary>
/// <param name="Code">Code typed by the client.</param>
public sealed record VerifyCodeRequest(string Code);

/// <summary>
/// HTTP body for the client to report a SINPE Móvil transfer.
/// </summary>
/// <param name="Amount">Amount transferred.</param>
/// <param name="Reference">Reference (confirmation number) of the transfer, optional.</param>
/// <param name="IdempotencyKey">Key generated by the portal so a double click or a retry registers the proof once.</param>
public sealed record SubmitProofRequest(decimal Amount, string? Reference, string IdempotencyKey);

/// <summary>
/// Endpoints of the client portal under <c>/public/bookings/{token}</c>. The token of the link is the credential for reading
/// the booking and asking for a code; every action that changes something also needs the portal session obtained by verifying
/// that code. All of them are rate limited per client address, and none of them accepts a photographer token.
/// </summary>
public static class PortalEndpoints
{
    /// <summary>
    /// Maps the portal endpoints.
    /// </summary>
    /// <param name="endpoints">Route builder.</param>
    /// <returns>The same route builder, for chaining.</returns>
    public static IEndpointRouteBuilder MapPortalEndpoints(this IEndpointRouteBuilder endpoints)
    {
        ArgumentNullException.ThrowIfNull(endpoints);

        var group = endpoints.MapGroup("/public/bookings/{token}").WithTags("Portal");

        group.MapGet("/", GetAsync).WithName("GetPortalBooking").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalReadPolicy);
        group.MapPost("/code", RequestCodeAsync).WithName("RequestPortalCode").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalCodePolicy);
        group.MapPost("/code/verify", VerifyCodeAsync).WithName("VerifyPortalCode").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalCodePolicy);
        group.MapPost("/payments", SubmitProofAsync)
            .WithName("SubmitPortalPaymentProof")
            .RequireAuthorization(ClientPortalExtensions.ClientPortalPolicy)
            .RequireRateLimiting(RateLimitingExtensions.PortalActionPolicy);

        return endpoints;
    }

    /// <summary>
    /// Reads the booking the link opens.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="handler">Query handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the booking as the client sees it; 404 when the token opens nothing.</returns>
    private static async Task<Ok<PortalBookingResponse>> GetAsync(
        string token,
        IQueryHandler<GetPortalBookingQuery, PortalBookingResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new GetPortalBookingQuery(token), cancellationToken));

    /// <summary>
    /// Sends a verification code to the email the photographer registered for the client.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>202 with where the code went (masked); 404, 409 <c>portal.email_missing</c>, 429 <c>portal.otp_rate_limited</c> or 503 <c>email.delivery_failed</c> otherwise.</returns>
    private static async Task<Accepted<PortalCodeSentResponse>> RequestCodeAsync(
        string token,
        ICommandHandler<RequestPortalCodeCommand, PortalCodeSentResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Accepted(
            (string?)null,
            await handler.HandleAsync(new RequestPortalCodeCommand(token), cancellationToken));

    /// <summary>
    /// Exchanges the code for a portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="request">Code typed by the client.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the session; 422 <c>portal.invalid_code</c> when the code is wrong, expired or spent.</returns>
    private static async Task<Ok<PortalSessionResponse>> VerifyCodeAsync(
        string token,
        VerifyCodeRequest request,
        ICommandHandler<VerifyPortalCodeCommand, PortalSessionResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new VerifyPortalCodeCommand(token, request.Code), cancellationToken));

    /// <summary>
    /// Reports a SINPE Móvil transfer for the photographer to verify. Needs the portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="request">Proof data.</param>
    /// <param name="user">Authenticated portal session.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the booking after the proof; 401 without a valid session; 404 when the session is for another booking.</returns>
    private static async Task<Ok<PortalBookingResponse>> SubmitProofAsync(
        string token,
        SubmitProofRequest request,
        ClaimsPrincipal user,
        ICommandHandler<SubmitPortalPaymentProofCommand, PortalBookingResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(
            new SubmitPortalPaymentProofCommand(token, user.GetPortalBookingId(), request.Amount, request.Reference, request.IdempotencyKey),
            cancellationToken));
}
