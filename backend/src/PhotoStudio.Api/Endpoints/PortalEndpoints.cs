using System.Security.Claims;
using Microsoft.AspNetCore.Http.HttpResults;
using PhotoStudio.Api.Cors;
using PhotoStudio.Api.RateLimiting;
using PhotoStudio.Application.Abstractions;
using PhotoStudio.Application.Portal;
using PhotoStudio.Application.Portal.GetBooking;
using PhotoStudio.Application.Portal.GetContract;
using PhotoStudio.Application.Portal.Galleries;
using PhotoStudio.Application.Portal.RequestCode;
using PhotoStudio.Application.Portal.SignContract;
using PhotoStudio.Application.Portal.SubmitProof;
using PhotoStudio.Application.Portal.VerifyCode;
using PhotoStudio.Domain.Bookings;
using PhotoStudio.Infrastructure.Portal;

namespace PhotoStudio.Api.Endpoints;

/// <summary>
/// HTTP body to verify the code the client received.
/// </summary>
/// <param name="Code">Code typed by the client.</param>
public sealed record VerifyCodeRequest(string Code);

/// <summary>
/// HTTP body for the client to report a SINPE Móvil transfer.
/// </summary>
/// <param name="Amount">Amount transferred.</param>
/// <param name="Reference">Reference (confirmation number) of the transfer, optional.</param>
/// <param name="IdempotencyKey">Key generated by the portal so a double click or a retry registers the proof once.</param>
public sealed record SubmitProofRequest(decimal Amount, string? Reference, string IdempotencyKey);

/// <summary>
/// HTTP body for the client to sign the contract they read.
/// </summary>
/// <param name="TemplateVersion">Version of the contract the client read, as the contract endpoint returned it.</param>
/// <param name="SignerName">Name typed by the signer.</param>
/// <param name="IdNumber">Identity number of the signer (cédula or DIMEX).</param>
/// <param name="ParticipantCount">Number of people in the session.</param>
/// <param name="SessionLocation">Place of the session, optional.</param>
/// <param name="ImageUse">What the client allows to do with the photos: <c>Authorized</c> or <c>NotAuthorized</c>.</param>
/// <param name="AcceptsTerms">Must be <see langword="true"/>: the client read and accepts the contract.</param>
public sealed record PortalSignContractRequest(
    string TemplateVersion,
    string SignerName,
    string IdNumber,
    int ParticipantCount,
    string? SessionLocation,
    ImageUse ImageUse,
    bool AcceptsTerms);

/// <summary>
/// HTTP body for the client to send the photos they chose.
/// </summary>
/// <param name="PhotoIds">Identifiers of the photos chosen.</param>
public sealed record SubmitSelectionRequest(IReadOnlyList<Guid>? PhotoIds);

/// <summary>
/// Endpoints of the client portal under <c>/public/bookings/{token}</c>. The token of the link is the credential for reading
/// the booking and asking for a code; every action that changes something also needs the portal session obtained by verifying
/// that code. All of them are rate limited per client address, and none of them accepts a photographer token.
/// </summary>
public static class PortalEndpoints
{
    /// <summary>
    /// Maps the portal endpoints.
    /// </summary>
    /// <param name="endpoints">Route builder.</param>
    /// <returns>The same route builder, for chaining.</returns>
    public static IEndpointRouteBuilder MapPortalEndpoints(this IEndpointRouteBuilder endpoints)
    {
        ArgumentNullException.ThrowIfNull(endpoints);

        var group = endpoints.MapGroup("/public/bookings/{token}").WithTags("Portal").RequireCors(PortalCorsExtensions.PolicyName);

        group.MapGet("/", GetAsync).WithName("GetPortalBooking").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalReadPolicy);
        group.MapPost("/code", RequestCodeAsync).WithName("RequestPortalCode").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalCodePolicy);
        group.MapPost("/code/verify", VerifyCodeAsync).WithName("VerifyPortalCode").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalCodePolicy);
        group.MapPost("/payments", SubmitProofAsync)
            .WithName("SubmitPortalPaymentProof")
            .RequireAuthorization(ClientPortalExtensions.ClientPortalPolicy)
            .RequireRateLimiting(RateLimitingExtensions.PortalActionPolicy);

        group.MapGet("/contract", GetContractAsync)
            .WithName("GetPortalContract")
            .RequireAuthorization(ClientPortalExtensions.ClientPortalPolicy)
            .RequireRateLimiting(RateLimitingExtensions.PortalReadPolicy);
        group.MapPost("/contract", SignContractAsync)
            .WithName("SignPortalContract")
            .RequireAuthorization(ClientPortalExtensions.ClientPortalPolicy)
            .RequireRateLimiting(RateLimitingExtensions.PortalActionPolicy);

        group.MapGet("/gallery/summary", GetGallerySummaryAsync).WithName("GetPortalGallerySummary").AllowAnonymous().RequireRateLimiting(RateLimitingExtensions.PortalReadPolicy);
        group.MapGet("/gallery", GetGalleryAsync)
            .WithName("GetPortalGallery")
            .RequireAuthorization(ClientPortalExtensions.ClientPortalPolicy)
            .RequireRateLimiting(RateLimitingExtensions.PortalReadPolicy);
        group.MapPost("/gallery/selection", SubmitSelectionAsync)
            .WithName("SubmitPortalSelection")
            .RequireAuthorization(ClientPortalExtensions.ClientPortalPolicy)
            .RequireRateLimiting(RateLimitingExtensions.PortalActionPolicy);

        return endpoints;
    }

    /// <summary>
    /// Tells whether the booking the link opens has a gallery the client can look at, and where it is. It needs only the link.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="handler">Query handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the state of the gallery; 404 when the token opens nothing or the gallery is not ready for the client.</returns>
    private static async Task<Ok<PortalGallerySummaryResponse>> GetGallerySummaryAsync(
        string token,
        IQueryHandler<GetPortalGallerySummaryQuery, PortalGallerySummaryResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new GetPortalGallerySummaryQuery(token), cancellationToken));

    /// <summary>
    /// Reads the gallery of the booking: the proofs and the terms to choose them. Needs the portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="user">Authenticated portal session.</param>
    /// <param name="handler">Query handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the gallery; 401 without a valid session; 404 when the session is for another booking or there is no gallery yet.</returns>
    private static async Task<Ok<PortalGalleryResponse>> GetGalleryAsync(
        string token,
        ClaimsPrincipal user,
        IQueryHandler<GetPortalGalleryQuery, PortalGalleryResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new GetPortalGalleryQuery(token, user.GetPortalBookingId()), cancellationToken));

    /// <summary>
    /// Sends the photos the client chose. From then on the selection is locked. Needs the portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="request">The photos chosen.</param>
    /// <param name="user">Authenticated portal session.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the gallery after the selection; 401 without a valid session; 404 when the session is for another booking; 409 when the selection is not open; 422 <c>gallery.invalid_selection</c> for photos that are none, repeated or not of the gallery.</returns>
    private static async Task<Ok<PortalGalleryResponse>> SubmitSelectionAsync(
        string token,
        SubmitSelectionRequest request,
        ClaimsPrincipal user,
        ICommandHandler<SubmitPortalSelectionCommand, PortalGalleryResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new SubmitPortalSelectionCommand(token, user.GetPortalBookingId(), request.PhotoIds ?? []), cancellationToken));

    /// <summary>
    /// Reads the booking the link opens.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="handler">Query handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the booking as the client sees it; 404 when the token opens nothing.</returns>
    private static async Task<Ok<PortalBookingResponse>> GetAsync(
        string token,
        IQueryHandler<GetPortalBookingQuery, PortalBookingResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new GetPortalBookingQuery(token), cancellationToken));

    /// <summary>
    /// Reads the contract of the booking the link opens, with the booking data filled in. Needs the portal session because the
    /// text holds the phone and, once signed, the identity number of the client.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="user">Authenticated portal session.</param>
    /// <param name="handler">Query handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the contract text; 401 without a valid session; 404 when the session is for another booking.</returns>
    private static async Task<Ok<PortalContractResponse>> GetContractAsync(
        string token,
        ClaimsPrincipal user,
        IQueryHandler<GetPortalContractQuery, PortalContractResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new GetPortalContractQuery(token, user.GetPortalBookingId()), cancellationToken));

    /// <summary>
    /// Signs the contract on behalf of the client. Needs the portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="request">Signature data.</param>
    /// <param name="user">Authenticated portal session.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the booking after signing; 401 without a valid session; 404 when the session is for another booking; 409 when the contract changed or is already signed; 422 for invalid values.</returns>
    private static async Task<Ok<PortalBookingResponse>> SignContractAsync(
        string token,
        PortalSignContractRequest request,
        ClaimsPrincipal user,
        ICommandHandler<SignPortalContractCommand, PortalBookingResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(
            new SignPortalContractCommand(
                token,
                user.GetPortalBookingId(),
                request.TemplateVersion,
                request.SignerName,
                request.IdNumber,
                request.ParticipantCount,
                request.SessionLocation,
                request.ImageUse,
                request.AcceptsTerms),
            cancellationToken));

    /// <summary>
    /// Sends a verification code to the email the photographer registered for the client.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>202 with where the code went (masked); 404, 409 <c>portal.email_missing</c>, 429 <c>portal.otp_rate_limited</c> or 503 <c>email.delivery_failed</c> otherwise.</returns>
    private static async Task<Accepted<PortalCodeSentResponse>> RequestCodeAsync(
        string token,
        ICommandHandler<RequestPortalCodeCommand, PortalCodeSentResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Accepted(
            (string?)null,
            await handler.HandleAsync(new RequestPortalCodeCommand(token), cancellationToken));

    /// <summary>
    /// Exchanges the code for a portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="request">Code typed by the client.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the session; 422 <c>portal.invalid_code</c> when the code is wrong, expired or spent.</returns>
    private static async Task<Ok<PortalSessionResponse>> VerifyCodeAsync(
        string token,
        VerifyCodeRequest request,
        ICommandHandler<VerifyPortalCodeCommand, PortalSessionResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(new VerifyPortalCodeCommand(token, request.Code), cancellationToken));

    /// <summary>
    /// Reports a SINPE Móvil transfer for the photographer to verify. Needs the portal session.
    /// </summary>
    /// <param name="token">Secret token of the link.</param>
    /// <param name="request">Proof data.</param>
    /// <param name="user">Authenticated portal session.</param>
    /// <param name="handler">Command handler.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>200 with the booking after the proof; 401 without a valid session; 404 when the session is for another booking.</returns>
    private static async Task<Ok<PortalBookingResponse>> SubmitProofAsync(
        string token,
        SubmitProofRequest request,
        ClaimsPrincipal user,
        ICommandHandler<SubmitPortalPaymentProofCommand, PortalBookingResponse> handler,
        CancellationToken cancellationToken) =>
        TypedResults.Ok(await handler.HandleAsync(
            new SubmitPortalPaymentProofCommand(token, user.GetPortalBookingId(), request.Amount, request.Reference, request.IdempotencyKey),
            cancellationToken));
}
